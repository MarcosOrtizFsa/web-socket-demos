<?php

declare(strict_types=1);

namespace App\Http\Requests;

use Illuminate\Foundation\Http\FormRequest;
use Illuminate\Validation\Rules\Password;

/**
 * Valida y normaliza el alta de una nueva cuenta.
 */
final class RegisterRequest extends FormRequest
{
    /**
     * El registro es público únicamente para visitantes no autenticados.
     */
    public function authorize(): bool
    {
        return true;
    }

    /**
     * Normaliza nombre y correo antes de comprobar unicidad.
     */
    protected function prepareForValidation(): void
    {
        $this->merge([
            'name' => trim((string) $this->input('name')),
            'email' => mb_strtolower(trim((string) $this->input('email'))),
        ]);
    }

    /**
     * Define los requisitos mínimos de una cuenta segura.
     *
     * @return array<string, mixed>
     */
    public function rules(): array
    {
        return [
            'name' => ['required', 'string', 'max:100'],
            'email' => ['required', 'email', 'max:255', 'unique:users,email'],
            'password' => ['required', 'confirmed', Password::min(8)],
        ];
    }
}
